const { test } = require('node:test');
const assert = require('node:assert/strict');
const User = require('../models/User');
const Class = require('../models/Class');
const Subject = require('../models/Subject');
const Student = require('../models/Student');
const Report = require('../models/NarrativeReport');
const service = require('../services/academic');

test('narratives persist by term and enforce ownership, enrollment and text limits', async (t) => {
  const id = '1'.repeat(24), studentId = '2'.repeat(24);
  const actor = { role: 'teacher', userId: '3'.repeat(24) };
  const subject = { _id: id, class: 'class1', teacher: 'another-teacher' };
  const cls = { adviser: actor.userId };
  const student = { class: 'class1', _id: studentId, subjects: [id], lastName: 'Alba', firstName: 'Ben' };
  const records = new Map();
  t.mock.method(Class, 'findById', () => ({ session: async () => cls }));
  t.mock.method(User, 'findOne', () => ({ session: async () => ({}) }));
  t.mock.method(Subject, 'findById', () => ({ session: async () => subject }));
  t.mock.method(Student, 'findById', async () => student);
  t.mock.method(Student, 'find', () => ({ sort: async () => [student] }));
  t.mock.method(Report, 'updateOne', async (filter, update) => records.set(filter.term, { ...filter, ...update.$set }));
  t.mock.method(Report, 'find', async (filter) => records.has(filter.term) ? [records.get(filter.term)] : []);
  const body = { term: 1, canDo: 'Reads confidently.\nWorks independently.', improving: 'Explaining ideas.' };
  await service.saveNarrativeReport(actor, id, studentId, body);
  assert.equal((await service.narrativeReports(actor, id, 1)).roster[0].canDo, body.canDo);
  assert.equal((await service.narrativeReports(actor, id, 2)).roster[0].canDo, '');
  await service.saveNarrativeReport(actor, id, studentId, { ...body, canDo: '', improving: '' });
  assert.equal((await service.narrativeReports(actor, id, 1)).roster[0].canDo, '');
  await assert.rejects(service.saveNarrativeReport(actor, id, studentId, { ...body, term: 4 }), { status: 400 });
  await assert.rejects(service.saveNarrativeReport(actor, id, studentId, { ...body, canDo: 'a'.repeat(10001) }), { status: 400 });
  student.class = 'different-class';
  await assert.rejects(service.saveNarrativeReport(actor, id, studentId, body), { status: 403 });
  student.class = 'class1';
  student.subjects = [];
  await assert.rejects(service.saveNarrativeReport(actor, id, studentId, body), { status: 403 });
  cls.adviser = 'other';
  await assert.rejects(service.narrativeReports(actor, id, 1), { status: 403 });
  await assert.rejects(service.saveNarrativeReport(actor, id, studentId, body), { status: 403 });
});
