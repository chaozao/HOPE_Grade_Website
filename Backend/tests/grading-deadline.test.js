const { test } = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const User = require('../models/User');
const Subject = require('../models/Subject');
const Leadership = require('../models/SubjectLeadership');
const Request = require('../models/GradeEditRequest');
const Audit = require('../models/AcademicAudit');
const access = require('../services/grading-access');
const service = require('../services/academic');
const teacherId = '1'.repeat(24), headId = '2'.repeat(24), subjectId = '3'.repeat(24), requestId = '4'.repeat(24);
const q = (value) => ({ session: async () => value });

test('deadline blocks ordinary teachers, permits subject head and grants, and prevents early requests', async (t) => {
  const actor = { role: 'teacher', userId: teacherId };
  const subject = { _id: subjectId, name: ' Math ', teacher: teacherId, gradeStatus: 'draft', gradeVersion: 1, class: 'class', save: async () => {} };
  const policy = { _id: 'policy', head: headId, revision: 2, deadline: new Date(Date.now() + 60000) };
  t.mock.method(Leadership, 'findOne', (filter) => { assert.equal(filter.name, 'math'); return q(policy); });
  t.mock.method(Leadership, 'updateOne', async () => {});
  t.mock.method(User, 'findOne', () => q({}));
  t.mock.method(Subject, 'findById', () => q(subject));
  t.mock.method(mongoose.connection, 'transaction', async (fn) => fn(null));
  t.mock.method(Audit, 'create', async () => {});
  let created;
  t.mock.method(Request, 'exists', () => q(false));
  t.mock.method(Request, 'create', async ([input]) => { created = input; return [{ ...input, _id: requestId }]; });
  assert.equal((await access.access(actor, subject)).canEdit, true);
  assert.equal((await access.access(actor, subject)).canRequest, false);
  await assert.rejects(service.requestEdit(actor, subjectId, { reason: 'Fix', version: 1 }), { status: 409 });
  policy.deadline = new Date(Date.now() - 1000);
  assert.equal((await access.access(actor, subject)).canEdit, false);
  await assert.rejects(access.requireEditing(actor, subject, null), { status: 409 });
  await assert.rejects(service.saveActivityScores(actor, subjectId, { term: 1, version: 1, grades: [] }), { status: 409 });
  await service.requestEdit(actor, subjectId, { reason: 'Fix', version: 1 });
  assert.equal(created.assignedHead, headId);
  assert.equal(created.policyRevision, 2);
  assert.equal((await access.access({ role: 'teacher', userId: headId }, subject)).canEdit, true);
  subject.editPermission = { teacher: teacherId, policyRevision: 2 };
  assert.equal((await access.access(actor, subject)).canEdit, true);
  assert.equal((await access.access(actor, subject)).canRequest, false);
  policy.revision++;
  assert.equal((await access.access(actor, subject)).canEdit, false);
});

test('only the current subject head reviews requests; stale policies cannot reopen grades', async (t) => {
  const subject = { _id: subjectId, name: 'Math', teacher: teacherId, gradeStatus: 'finalized', gradeVersion: 5, save: async () => {} };
  const policy = { head: headId, revision: 2, deadline: new Date(Date.now() - 1000) };
  const request = { _id: requestId, subject: subjectId, requestedBy: teacherId, status: 'pending', policyRevision: 2, gradeVersion: 5, save: async () => {} };
  t.mock.method(User, 'findOne', () => q({}));
  t.mock.method(Subject, 'findById', () => q(subject));
  t.mock.method(Leadership, 'findOne', () => q(policy));
  t.mock.method(Leadership, 'updateOne', async () => {});
  t.mock.method(Request, 'findById', () => q(request));
  t.mock.method(Audit, 'create', async () => {});
  t.mock.method(mongoose.connection, 'transaction', async (fn) => fn(null));
  await assert.rejects(service.reviewRequest({ role: 'teacher', userId: teacherId }, requestId, { decision: 'approved' }), { status: 403 });
  request.policyRevision = 1;
  await assert.rejects(service.reviewRequest({ role: 'teacher', userId: headId }, requestId, { decision: 'approved' }), { status: 409 });
  request.policyRevision = 2;
  await service.reviewRequest({ role: 'teacher', userId: headId }, requestId, { decision: 'approved' });
  assert.equal(subject.gradeStatus, 'draft');
  assert.equal(request.status, 'approved');
  assert.deepEqual(subject.editPermission, { teacher: teacherId, policyRevision: 2 });
});
